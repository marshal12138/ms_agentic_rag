#!/usr/bin/env python3
"""Build a compact index of every persisted teacher-PE experiment result."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any


HERE = Path(__file__).resolve().parent
RESULTS = HERE / "results"
OUTPUT = HERE / "RESULTS_INDEX.md"


def fmt(value: Any, digits: int = 4) -> str:
    if value is None:
        return "-"
    return f"{float(value):.{digits}f}"


def selected_rows(path: Path, metrics: dict[str, Any]) -> list[tuple[str, dict[str, Any]]]:
    if "selected" in metrics:
        run_path = path / "run.json"
        run = json.loads(run_path.read_text(encoding="utf-8")) if run_path.exists() else {}
        requested = str(run.get("split") or "selected")
        if requested == "all" and "dev" in metrics and "holdout" in metrics:
            return [("dev", metrics["dev"]), ("holdout", metrics["holdout"])]
        return [(requested, metrics["selected"])]
    if "dev" in metrics and "holdout" in metrics and "threshold" in metrics:
        return [("dev", metrics["dev"]), ("holdout", metrics["holdout"])]
    if "i_binary" in metrics:
        run_path = path / "run.json"
        run = json.loads(run_path.read_text(encoding="utf-8")) if run_path.exists() else {}
        return [(str(run.get("split") or "selected"), metrics)]
    return []


def row_values(result_dir: Path, split: str, metrics: dict[str, Any]) -> list[str]:
    run_path = result_dir / "run.json"
    run = json.loads(run_path.read_text(encoding="utf-8")) if run_path.exists() else {}
    if "i_binary" in metrics:
        i_metrics = metrics["i_binary"]
        parse_rate = metrics.get("parse_rate")
        tokens = (metrics.get("output_length") or {}).get("avg_completion_tokens")
    else:
        i_metrics = metrics
        parse_rate = 1.0
        tokens = 1 if "threshold" in metrics else None
    wall = run.get("wall_elapsed_s")
    if wall is None:
        wall = run.get("cost", {}).get("avg_serial_request_latency_s")
    invalid_parts = [part for part in result_dir.parts if part.startswith("_invalid")]
    invalid = bool(invalid_parts)
    return [
        f"`{result_dir.relative_to(RESULTS)}`",
        split,
        str(metrics.get("case_count") or "-"),
        fmt(i_metrics.get("precision")),
        fmt(i_metrics.get("recall")),
        fmt(i_metrics.get("f1")),
        fmt(parse_rate),
        fmt(wall, 2),
        fmt(tokens, 1),
        f"INVALID: {invalid_parts[-1]}" if invalid else "valid",
    ]


def main() -> None:
    rows: list[list[str]] = []
    for metrics_path in sorted(RESULTS.rglob("metrics.json")):
        result_dir = metrics_path.parent
        metrics = json.loads(metrics_path.read_text(encoding="utf-8"))
        for split, selected in selected_rows(result_dir, metrics):
            rows.append(row_values(result_dir, split, selected))

    lines = [
        "# Teacher PE Results Index",
        "",
        "Generated by `build_results_index.py`. Invalid leakage runs are retained only for audit and must never be selected.",
        "",
        "| Result | Split | N | I precision | I recall | I F1 | Parse | Wall/serial s | Avg tokens | Validity |",
        "| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | --- |",
    ]
    lines.extend("| " + " | ".join(row) + " |" for row in rows)
    lines.append("")
    OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {len(rows)} rows to {OUTPUT}")


if __name__ == "__main__":
    main()
